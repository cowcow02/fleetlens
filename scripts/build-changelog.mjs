#!/usr/bin/env node
// Release workflows run this before publishing so the bundled content can
// never be stale. Run via `pnpm changelog:sync` after editing either CHANGELOG.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");

const targets = [
  {
    source: join(repoRoot, "CHANGELOG.md"),
    out: join(repoRoot, "apps/web/lib/changelog-data.generated.ts"),
    label: "personal",
  },
  {
    source: join(repoRoot, "packages/team-server/CHANGELOG.md"),
    out: join(repoRoot, "packages/team-server/src/lib/changelog-data.generated.ts"),
    label: "team",
  },
];

for (const { source, out, label } of targets) {
  const raw = readFileSync(source, "utf8");
  const escaped = JSON.stringify(raw);
  const body = `// AUTOGENERATED by scripts/build-changelog.mjs from ${label === "personal" ? "CHANGELOG.md" : "packages/team-server/CHANGELOG.md"}.
// Do not edit by hand — run \`pnpm changelog:sync\`.
export const RAW_CHANGELOG = ${escaped};
`;
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, body, "utf8");
  console.log(`✓ ${label}: ${source} → ${out}`);
}
